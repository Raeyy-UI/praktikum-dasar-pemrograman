def hitung_luas_persegi_panjang(panjang, lebar):
    luas = panjang * lebar
    return luas

# Memanggil fungsi dengan panjang 12 dan lebar 5
hasil_luas = hitung_luas_persegi_panjang(12, 5)

# Menampilkan hasil yang disimpan di dalam variabel
print(f"Panjang : 12")
print(f"Lebar   : 5")
print(f"Luas Persegi Panjang: {hasil_luas}")